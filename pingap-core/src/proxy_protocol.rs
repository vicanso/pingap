    #[test]
    fn test_parse_v2_tlvs_truncated_returns_none() {
        // Truncated TLV header (< 3 bytes).
        assert_eq!(None, parse_v2_tlvs(&[0x01]));
        assert_eq!(None, parse_v2_tlvs(&[0x01, 0x00]));
        // Truncated TLV value.
        assert_eq!(
            None,
            parse_v2_tlvs(&[PP2_TYPE_ALPN, 0x00, 0x04, b'h', b'2'])
        );
        // Valid TLV followed by truncated TLV.
        let mut partial = tlv(PP2_TYPE_NOOP, b"ab");
        partial.extend_from_slice(&[PP2_TYPE_AUTHORITY, 0x00, 0x03, b'x']);
        assert_eq!(None, parse_v2_tlvs(&partial));
        // PP2_TYPE_SSL shorter than 5 bytes (client + verify).
        assert_eq!(None, parse_v2_tlvs(&tlv(PP2_TYPE_SSL, &[0x01, 0, 0, 0])));
        // PP2_TYPE_SSL with truncated sub-TLV header or value.
        assert_eq!(
            None,
            parse_v2_tlvs(&tlv(PP2_TYPE_SSL, &[0x01, 0, 0, 0, 0, 0x21, 0x00]))
        );
        assert_eq!(
            None,
            parse_v2_tlvs(&tlv(
                PP2_TYPE_SSL,
                &[0x01, 0, 0, 0, 0, PP2_SUBTYPE_SSL_VERSION, 0x00, 0x05, b'1']
            ))
        );
    }
