/// The names a configuration has for the versions, in lower case.
pub const PROXY_PROTOCOL_VERSIONS: [&str; 2] = ["v1", "v2"];

/// Maximum byte length of a version 1 or version 2 PROXY protocol header
/// written by [`new_proxy_protocol_header`].
pub const MAX_PROXY_PROTOCOL_HEADER_LEN: usize = 107;

const V2_SIGNATURE: &[u8] = b"\r\n\r\n\0\r\nQUIT\n";
/// Version 2 and the command: `LOCAL` for a connection of the proxy's
/// own, `PROXY` for one that is passed on.
const V2_LOCAL: u8 = 0x20;
const V2_PROXY: u8 = 0x21;
/// The address family and the transport: TCP over IPv4, TCP over IPv6.
const V2_TCP4: u8 = 0x11;
const V2_TCP6: u8 = 0x21;

/// PROXY protocol v2 TLV type: ALPN protocol negotiated on the connection.
pub const PP2_TYPE_ALPN: u8 = 0x01;
/// PROXY protocol v2 TLV type: host name value from SNI / authority.
pub const PP2_TYPE_AUTHORITY: u8 = 0x02;
/// PROXY protocol v2 TLV type: CRC32c checksum of the PROXY v2 header.
pub const PP2_TYPE_CRC32C: u8 = 0x03;
/// PROXY protocol v2 TLV type: padding bytes that must be ignored.
pub const PP2_TYPE_NOOP: u8 = 0x04;
/// PROXY protocol v2 TLV type: unique connection identifier generated by the proxy.
pub const PP2_TYPE_UNIQUE_ID: u8 = 0x05;
/// PROXY protocol v2 TLV type: SSL/TLS connection attributes container.
pub const PP2_TYPE_SSL: u8 = 0x20;
/// PROXY protocol v2 SSL sub-TLV type: TLS protocol version string.
pub const PP2_SUBTYPE_SSL_VERSION: u8 = 0x21;
/// PROXY protocol v2 SSL sub-TLV type: client certificate Common Name.
pub const PP2_SUBTYPE_SSL_CN: u8 = 0x22;
/// PROXY protocol v2 SSL sub-TLV type: negotiated TLS cipher suite name.
pub const PP2_SUBTYPE_SSL_CIPHER: u8 = 0x23;
/// PROXY protocol v2 SSL sub-TLV type: client certificate signature algorithm.
pub const PP2_SUBTYPE_SSL_SIG_ALG: u8 = 0x24;
/// PROXY protocol v2 SSL sub-TLV type: client certificate key algorithm.
pub const PP2_SUBTYPE_SSL_KEY_ALG: u8 = 0x25;
/// PROXY protocol v2 TLV type: network namespace name.
pub const PP2_TYPE_NETNS: u8 = 0x30;
/// PROXY protocol v2 TLV type: AWS vendor-specific extension container.
pub const PP2_TYPE_AWS: u8 = 0xEA;
/// PROXY protocol v2 AWS sub-TLV subtype: VPC Endpoint ID (`vpce-...`).
pub const PP2_SUBTYPE_AWS_VPCE_ID: u8 = 0x01;

const MAX_CUSTOM_TLVS: usize = 16;
const HEX_DIGITS: &[u8; 16] = b"0123456789abcdef";

/// Type-Length-Value attributes extracted from an inbound PROXY protocol v2 header.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct ProxyProtocolTlvs {
    /// Negotiated application-layer protocol (`PP2_TYPE_ALPN`).
    pub alpn: Option<String>,
    /// Authority / SNI hostname (`PP2_TYPE_AUTHORITY`).
    pub authority: Option<String>,
    /// Connection unique ID (`PP2_TYPE_UNIQUE_ID`), UTF-8 when printable ASCII or lowercase hex.
    pub unique_id: Option<String>,
    /// Network namespace name (`PP2_TYPE_NETNS`).
    pub netns: Option<String>,
    /// TLS version reported in `PP2_TYPE_SSL` (`PP2_SUBTYPE_SSL_VERSION`).
    pub tls_version: Option<String>,
    /// Client certificate CN reported in `PP2_TYPE_SSL` (`PP2_SUBTYPE_SSL_CN`).
    pub tls_cn: Option<String>,
    /// TLS cipher suite reported in `PP2_TYPE_SSL` (`PP2_SUBTYPE_SSL_CIPHER`).
    pub tls_cipher: Option<String>,
    /// AWS VPC Endpoint ID reported in `PP2_TYPE_AWS` (`PP2_SUBTYPE_AWS_VPCE_ID`).
    pub aws_vpce_id: Option<String>,
    /// Non-NOOP unrecognized or custom TLV payloads, capped at 16 entries.
    pub custom: Vec<(u8, Vec<u8>)>,
}

fn is_printable_ascii(bytes: &[u8]) -> bool {
    bytes.iter().all(|b| (0x20..=0x7E).contains(b))
}

fn push_lower_hex(out: &mut String, bytes: &[u8]) {
    for &b in bytes {
        out.push(HEX_DIGITS[(b >> 4) as usize] as char);
        out.push(HEX_DIGITS[(b & 0x0f) as usize] as char);
    }
}

fn encode_lower_hex(bytes: &[u8]) -> String {
    let mut out = String::with_capacity(bytes.len() * 2);
    push_lower_hex(&mut out, bytes);
    out
}

impl ProxyProtocolTlvs {
    /// Returns `true` when no known or custom TLV values were captured.
    pub fn is_empty(&self) -> bool {
        self.alpn.is_none()
            && self.authority.is_none()
            && self.unique_id.is_none()
            && self.netns.is_none()
            && self.tls_version.is_none()
            && self.tls_cn.is_none()
            && self.tls_cipher.is_none()
            && self.aws_vpce_id.is_none()
            && self.custom.is_empty()
    }

    fn custom_tlv_string(&self, tlv_type: u8) -> Option<Cow<'_, str>> {
        let (_, payload) = self.custom.iter().find(|(t, _)| *t == tlv_type)?;
        if is_printable_ascii(payload) {
            std::str::from_utf8(payload).ok().map(Cow::Borrowed)
        } else {
            let mut out = String::with_capacity(2 + payload.len() * 2);
            out.push_str("0x");
            push_lower_hex(&mut out, payload);
            Some(Cow::Owned(out))
        }
    }

    /// Returns the string representation for a PROXY v2 TLV type.
    ///
    /// Known scalar TLVs (`0x01`, `0x02`, `0x05`, `0x30`, `0xEA`) return their
    /// decoded field; unrecognized or non-VPCE `0xEA` TLVs fall back to
    /// [`Self::custom`], returning `&str` when printable ASCII or `0x<lower-hex>`.
    pub fn get_tlv_string(&self, tlv_type: u8) -> Option<Cow<'_, str>> {
        match tlv_type {
            PP2_TYPE_ALPN => self.alpn.as_deref().map(Cow::Borrowed),
            PP2_TYPE_AUTHORITY => self.authority.as_deref().map(Cow::Borrowed),
            PP2_TYPE_UNIQUE_ID => self.unique_id.as_deref().map(Cow::Borrowed),
            PP2_TYPE_NETNS => self.netns.as_deref().map(Cow::Borrowed),
            PP2_TYPE_AWS => self
                .aws_vpce_id
                .as_deref()
                .map(Cow::Borrowed)
                .or_else(|| self.custom_tlv_string(tlv_type)),
            _ => self.custom_tlv_string(tlv_type),
        }
    }
}

fn parse_tlv_frame(buf: &[u8]) -> Option<(u8, &[u8], &[u8])> {
    if buf.len() < 3 {
        return None;
    }
    let tlv_type = buf[0];
    let len = usize::from(u16::from_be_bytes([buf[1], buf[2]]));
    let after_header = &buf[3..];
    if after_header.len() < len {
        return None;
    }
    let (value, rest) = after_header.split_at(len);
    Some((tlv_type, value, rest))
}

fn decode_utf8_field(value: &[u8], target: &mut Option<String>) {
    if let Ok(text) = std::str::from_utf8(value) {
        *target = Some(text.to_string());
    }
}

fn decode_unique_id(value: &[u8]) -> String {
    if is_printable_ascii(value)
        && let Ok(text) = std::str::from_utf8(value)
    {
        return text.to_string();
    }
    encode_lower_hex(value)
}

fn push_custom_tlv(
    custom: &mut Vec<(u8, Vec<u8>)>,
    tlv_type: u8,
    value: &[u8],
) {
    if custom.len() < MAX_CUSTOM_TLVS {
        custom.push((tlv_type, value.to_vec()));
    }
}

fn parse_ssl_sub_tlvs(
    value: &[u8],
    tlvs: &mut ProxyProtocolTlvs,
) -> Option<()> {
    if value.len() < 5 {
        return None;
    }
    let mut rest = &value[5..];
    while !rest.is_empty() {
        let (sub_type, sub_value, next) = parse_tlv_frame(rest)?;
        rest = next;
        match sub_type {
            PP2_SUBTYPE_SSL_VERSION => {
                decode_utf8_field(sub_value, &mut tlvs.tls_version);
            },
            PP2_SUBTYPE_SSL_CN => {
                decode_utf8_field(sub_value, &mut tlvs.tls_cn);
            },
            PP2_SUBTYPE_SSL_CIPHER => {
                decode_utf8_field(sub_value, &mut tlvs.tls_cipher);
            },
            _ => {},
        }
    }
    Some(())
}

fn parse_aws_tlv(value: &[u8], tlvs: &mut ProxyProtocolTlvs) {
    if value.first() == Some(&PP2_SUBTYPE_AWS_VPCE_ID)
        && let Ok(vpce_id) = std::str::from_utf8(&value[1..])
    {
        tlvs.aws_vpce_id = Some(vpce_id.to_string());
    } else {
        push_custom_tlv(&mut tlvs.custom, PP2_TYPE_AWS, value);
    }
}

/// Parses PROXY protocol v2 TLV bytes following the fixed header and address block.
///
/// Returns `None` if any TLV (or `PP2_TYPE_SSL` sub-TLV) has truncated framing.
pub fn parse_v2_tlvs(buf: &[u8]) -> Option<ProxyProtocolTlvs> {
    let mut tlvs = ProxyProtocolTlvs::default();
    let mut rest = buf;
    while !rest.is_empty() {
        let (tlv_type, value, next) = parse_tlv_frame(rest)?;
        rest = next;
        match tlv_type {
            PP2_TYPE_NOOP => {},
            PP2_TYPE_ALPN => decode_utf8_field(value, &mut tlvs.alpn),
            PP2_TYPE_AUTHORITY => decode_utf8_field(value, &mut tlvs.authority),
            PP2_TYPE_UNIQUE_ID => {
                tlvs.unique_id = Some(decode_unique_id(value));
            },
            PP2_TYPE_NETNS => decode_utf8_field(value, &mut tlvs.netns),
            PP2_TYPE_SSL => parse_ssl_sub_tlvs(value, &mut tlvs)?,
            PP2_TYPE_AWS => parse_aws_tlv(value, &mut tlvs),
            _ => push_custom_tlv(&mut tlvs.custom, tlv_type, value),
        }
    }
    Some(tlvs)
}

/// A PROXY protocol header stored inline on the stack without heap allocation.
#[derive(Clone, Copy, Eq)]
pub struct ProxyProtocolHeader {
    buf: [u8; MAX_PROXY_PROTOCOL_HEADER_LEN],
    len: u8,
}

impl ProxyProtocolHeader {
    const fn empty() -> Self {
        Self {
            buf: [0u8; MAX_PROXY_PROTOCOL_HEADER_LEN],
            len: 0,
        }
    }

    fn from_slice(bytes: &[u8]) -> Self {
        let mut header = Self::empty();
        header.push_slice(bytes);
        header
    }

    fn push_slice(&mut self, bytes: &[u8]) {
        let start = self.len as usize;
        let count = bytes.len().min(MAX_PROXY_PROTOCOL_HEADER_LEN - start);
        self.buf[start..start + count].copy_from_slice(&bytes[..count]);
        self.len = (start + count) as u8;
    }

    fn push_byte(&mut self, byte: u8) {
        self.push_slice(&[byte]);
    }

    /// Returns the encoded header bytes.
    #[inline]
    pub fn as_slice(&self) -> &[u8] {
        &self.buf[..self.len as usize]
    }
}

impl std::fmt::Debug for ProxyProtocolHeader {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        self.as_slice().fmt(f)
    }
}

impl std::ops::Deref for ProxyProtocolHeader {
    type Target = [u8];

    #[inline]
    fn deref(&self) -> &Self::Target {
        self.as_slice()
    }
}

impl AsRef<[u8]> for ProxyProtocolHeader {
    #[inline]
    fn as_ref(&self) -> &[u8] {
        self.as_slice()
    }
}

impl PartialEq for ProxyProtocolHeader {
    fn eq(&self, other: &Self) -> bool {
        self.as_slice() == other.as_slice()
    }
}

impl PartialEq<[u8]> for ProxyProtocolHeader {
    fn eq(&self, other: &[u8]) -> bool {
        self.as_slice() == other
    }
}

impl PartialEq<&[u8]> for ProxyProtocolHeader {
    fn eq(&self, other: &&[u8]) -> bool {
        self.as_slice() == *other
    }
}

impl PartialEq<Vec<u8>> for ProxyProtocolHeader {
    fn eq(&self, other: &Vec<u8>) -> bool {
        self.as_slice() == other.as_slice()
    }
}

impl PartialEq<ProxyProtocolHeader> for Vec<u8> {
    fn eq(&self, other: &ProxyProtocolHeader) -> bool {
        self.as_slice() == other.as_slice()
    }
}

struct HeaderWriter<'a>(&'a mut ProxyProtocolHeader);

impl std::fmt::Write for HeaderWriter<'_> {
    fn write_str(&mut self, s: &str) -> std::fmt::Result {
        self.0.push_slice(s.as_bytes());
        Ok(())
    }
}

/// The form of the header.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProxyProtocolVersion {
    /// A line of text: `PROXY TCP4 192.0.2.1 198.51.100.1 56324 443\r\n`.
    V1,
    /// The binary form.
    V2,
}

impl ProxyProtocolVersion {
    /// `v1` or `v2`, in any case. `None` for anything else.
    pub fn parse(value: &str) -> Option<Self> {
        match value.trim().to_ascii_lowercase().as_str() {
            "v1" => Some(Self::V1),
            "v2" => Some(Self::V2),
            _ => None,
        }
    }
}

/// Both ends in one family, which is all a header has room for: IPv4 where
/// both are, the IPv4-mapped addresses of a dual-stack socket included,
/// and IPv6 otherwise, with the IPv4 end mapped into it.
fn same_family(
    source: SocketAddr,
    destination: SocketAddr,
) -> (SocketAddr, SocketAddr) {
    let canonical = |addr: SocketAddr| {
        SocketAddr::new(addr.ip().to_canonical(), addr.port())
    };
    let (source, destination) = (canonical(source), canonical(destination));
    if source.is_ipv4() == destination.is_ipv4() {
        return (source, destination);
    }
    let mapped = |addr: SocketAddr| match addr.ip() {
        IpAddr::V4(ip) => {
            SocketAddr::new(IpAddr::V6(ip.to_ipv6_mapped()), addr.port())
        },
        IpAddr::V6(_) => addr,
    };
    (mapped(source), mapped(destination))
}

/// Writes an address as version 1 formats it directly into `out`. An IPv6
/// address is groups of hexadecimal digits there and nothing else: `Display`
/// ends an IPv4-mapped one in dotted decimals.
fn write_v1_ip(out: &mut ProxyProtocolHeader, ip: IpAddr) {
    let mut writer = HeaderWriter(out);
    match ip {
        IpAddr::V6(v6) if v6.to_ipv4_mapped().is_some() => {
            let segments = v6.segments();
            let _ =
                write!(writer, "::ffff:{:x}:{:x}", segments[6], segments[7]);
        },
        _ => {
            let _ = write!(writer, "{ip}");
        },
    }
}

fn new_v1_header(
    source: SocketAddr,
    destination: SocketAddr,
) -> ProxyProtocolHeader {
    let mut header = ProxyProtocolHeader::empty();
    let family = if source.is_ipv4() {
        b"PROXY TCP4 ".as_slice()
    } else {
        b"PROXY TCP6 ".as_slice()
    };
    header.push_slice(family);
    write_v1_ip(&mut header, source.ip());
    header.push_byte(b' ');
    write_v1_ip(&mut header, destination.ip());
    let _ = write!(
        HeaderWriter(&mut header),
        " {} {}\r\n",
        source.port(),
        destination.port()
    );
    header
}

fn new_v2_header(
    source: SocketAddr,
    destination: SocketAddr,
) -> ProxyProtocolHeader {
    let mut header = ProxyProtocolHeader::from_slice(V2_SIGNATURE);
    header.push_byte(V2_PROXY);
    match (source.ip(), destination.ip()) {
        (IpAddr::V4(src_ip), IpAddr::V4(dst_ip)) => {
            header.push_byte(V2_TCP4);
            header.push_slice(&12u16.to_be_bytes());
            header.push_slice(&src_ip.octets());
            header.push_slice(&dst_ip.octets());
        },
        (src_ip, dst_ip) => {
            // of one family by now: neither is IPv4
            header.push_byte(V2_TCP6);
            header.push_slice(&36u16.to_be_bytes());
            for ip in [src_ip, dst_ip] {
                if let IpAddr::V6(v6) = ip {
                    header.push_slice(&v6.octets());
                }
            }
        },
    }
    header.push_slice(&source.port().to_be_bytes());
    header.push_slice(&destination.port().to_be_bytes());
    header
}

/// The header a connection starts with, formatted inline without heap allocation.
///
/// `addresses` are where the client comes from and what of this proxy it
/// came to. `None` is for a connection that is made for nobody, a health
/// check: the backend is told to go by the connection itself (`LOCAL` in
/// version 2; version 1 has `UNKNOWN` for it).
///
/// A client that is passed on without an address to give would be
/// `PROXY` with no family in version 2, which is not written here: every
/// listener of this proxy is a TCP one, and its clients have addresses.
pub fn new_proxy_protocol_header(
    version: ProxyProtocolVersion,
    addresses: Option<(SocketAddr, SocketAddr)>,
) -> ProxyProtocolHeader {
    let addresses =
        addresses.map(|(source, destination)| same_family(source, destination));
    match (version, addresses) {
        (ProxyProtocolVersion::V1, None) => {
            ProxyProtocolHeader::from_slice(b"PROXY UNKNOWN\r\n")
        },
        (ProxyProtocolVersion::V1, Some((source, destination))) => {
            new_v1_header(source, destination)
        },
        (ProxyProtocolVersion::V2, None) => {
            let mut header = ProxyProtocolHeader::from_slice(V2_SIGNATURE);
            // LOCAL, no family, nothing that follows
            header.push_slice(&[V2_LOCAL, 0, 0, 0]);
            header
        },
        (ProxyProtocolVersion::V2, Some((source, destination))) => {
            new_v2_header(source, destination)
        },
    }
}

/// Whether `session`'s client TCP connection can carry another request after
/// this one finishes.
///
/// An upstream connection that starts with a per-client PROXY protocol header
/// is pinned to that client `(ip, port)` and cannot be handed to any other
/// client connection. When the downstream connection is closing after this
/// request (for example HTTP/1.0 without `Connection: keep-alive`, HTTP/1.1
/// with `Connection: close`, or a connection that has reached its keepalive
/// reuse limit), keeping the upstream connection in Pingora's shared idle pool
/// can never produce a hit and only evicts reusable pooled connections.
pub fn downstream_will_reuse(session: &pingora::proxy::Session) -> bool {
    match session.as_downstream() {
        pingora::protocols::http::ServerSession::H1(h1) => h1.will_keepalive(),
        pingora::protocols::http::ServerSession::H2(_) => true,
        _ => false,
    }
}

/// What pingora's own connector takes from the peer for the socket it
/// opens. A connector that stands in for it is given the address and
/// nothing else, so these come with it.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct ProxyProtocolConnectOptions {
    /// How long connecting and sending the header may take.
    pub connection_timeout: Option<Duration>,
    /// The size of the receive buffer of the socket (`SO_RCVBUF`), where
    /// one is set.
    pub tcp_recv_buf: Option<usize>,
    /// Whether the connection is opened with TCP Fast Open.
    pub tcp_fast_open: bool,
}

/// Connects to a backend and writes a PROXY protocol header as the first
/// bytes of the connection.
#[derive(Debug)]
pub struct ProxyProtocolConnector {
    header: ProxyProtocolHeader,
    options: ProxyProtocolConnectOptions,
}

/// The failure of a connection attempt as pingora has it, which is what
/// says whether the request may go to another backend and what the client
/// is answered.
fn new_connect_error(e: std::io::Error, addr: &PeerAddr) -> Box<Error> {
    let etype = match e.kind() {
        ErrorKind::ConnectionRefused => ErrorType::ConnectRefused,
        ErrorKind::TimedOut => ErrorType::ConnectTimedout,
        ErrorKind::AddrNotAvailable
        | ErrorKind::PermissionDenied
        | ErrorKind::AddrInUse => ErrorType::InternalError,
        ErrorKind::NetworkUnreachable | ErrorKind::HostUnreachable => {
            ErrorType::ConnectNoRoute
        },
        _ => ErrorType::ConnectError,
    };
    Error::because(etype, format!("Fail to connect to {addr}"), e)
}

impl ProxyProtocolConnector {
    /// A connector that starts every connection with `header`.
    pub fn new(
        header: ProxyProtocolHeader,
        options: ProxyProtocolConnectOptions,
    ) -> Self {
        Self { header, options }
    }

    /// The header every connection of this connector starts with.
    pub fn header(&self) -> &[u8] {
        self.header.as_slice()
    }

    fn set_socket(&self, socket: &TcpSocket) -> Result<()> {
        #[cfg(unix)]
        let raw = socket.as_raw_fd();
        #[cfg(windows)]
        let raw = socket.as_raw_socket();
        if self.options.tcp_fast_open {
            set_tcp_fastopen_connect(raw)?;
        }
        if let Some(size) = self.options.tcp_recv_buf {
            set_recv_buf(raw, size)?;
        }
        Ok(())
    }

    async fn connect_and_send(&self, addr: &PeerAddr) -> Result<Stream> {
        // Nothing of a request is on its way yet: a header that cannot be
        // sent is a connection that was not made.
        let not_sent = |e: std::io::Error| {
            Error::because(
                ErrorType::ConnectError,
                format!("Fail to send the PROXY protocol header to {addr}"),
                e,
            )
        };
        match addr {
            PeerAddr::Inet(inet) => {
                let socket = if inet.is_ipv4() {
                    TcpSocket::new_v4()
                } else {
                    TcpSocket::new_v6()
                }
                .or_err(ErrorType::SocketError, "failed to create socket")
                .map_err(|e| {
                    Error::because(
                        ErrorType::InternalError,
                        format!("Fail to connect to {addr}"),
                        e,
                    )
                })?;
                // An option the kernel refuses is a connection that was
                // not made, as it is for pingora's own connector.
                self.set_socket(&socket).map_err(|e| {
                    e.more_context(format!("Fail to connect to {addr}"))
                })?;
                let mut stream = socket
                    .connect(*inet)
                    .await
                    .map_err(|e| new_connect_error(e, addr))?;
                stream.write_all(&self.header).await.map_err(not_sent)?;
                Ok(stream.into())
            },
            #[cfg(unix)]
            PeerAddr::Unix(unix) => {
                let Some(path) = unix.as_pathname() else {
                    return Error::e_explain(
                        ErrorType::InternalError,
                        format!("{addr} is not the path of a socket"),
                    );
                };
                let mut stream = connect_uds(path).await?;
                stream.write_all(&self.header).await.map_err(not_sent)?;
                Ok(stream.into())
            },
        }
    }
}

/// `connecting` to `addr`, given up after `limit` where there is one.
async fn within<T>(
    limit: Option<Duration>,
    addr: &PeerAddr,
    connecting: impl Future<Output = Result<T>>,
) -> Result<T> {
    let Some(limit) = limit else {
        return connecting.await;
    };
    tokio::time::timeout(limit, connecting).await.map_err(|e| {
        Error::because(
            ErrorType::ConnectTimedout,
            format!("timeout {limit:?} connecting to server {addr}"),
            e,
        )
    })?
}

#[async_trait]
impl Connect for ProxyProtocolConnector {
    async fn connect(&self, addr: &PeerAddr) -> Result<Stream> {
        within(
            self.options.connection_timeout,
            addr,
            self.connect_and_send(addr),
        )
        .await
    }
}

